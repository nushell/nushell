#[test]
fn rejects_a_keyword_as_the_tool() -> Result {
    let err = test()
        .run_with_data("generate completions if --source help", HELP)
        .expect_shell_error()?;
    assert_matches!(
        err,
        ShellError::IncorrectValue { msg, .. } if msg.contains("`if` is a nushell keyword")
    );
    Ok(())
}

#[test]
fn rejects_an_unknown_source() -> Result {
    test()
        .run("generate completions tool --source bash")
        .expect_error_code_eq("nu::shell::incorrect_value")
}

#[test]
fn reports_when_nothing_is_found() -> Result {
    let err = test()
        .run_with_data("generate completions tool --source help", "no options here")
        .expect_shell_error()?;
    assert_contains("couldn't generate completions for `tool`", err.to_string());
    Ok(())
}
