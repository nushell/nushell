const HELP: &str = "\
Usage: tool [OPTIONS]

Options:
  -o, --output <FILE>   Write output to FILE
      --color[=WHEN]    Color the output
      --format <FMT>    Output format [possible values: json, true, 2]
  -h, --help            Print help
";

/// clap lists a command's subcommands in its help.
const CLAP_HELP: &str = "\
Usage: tool pip <COMMAND>

Commands:
  install  Install packages [aliases: i]
  list     List installed packages

Options:
  -h, --help  Print help
";

const FISH: &str = "\
complete -c tool -n __fish_use_subcommand -a build -d 'Compile the package'
complete -c tool -n '__fish_seen_subcommand_from build' -l release -d 'Build in release mode'
complete -c tool -n '__fish_seen_subcommand_from build' -l profile -x -a 'dev release' -d 'Profile'
";

const ZSH: &str = "#compdef tool
_tool-build () {
  _arguments '(-r --release)'{-r,--release}'[Build in release mode]' \\
    '--color=[when to color]:when:(always never)'
}
";

const CARAPACE: &str = r#"{
    "Name": "tool",
    "Commands": [{
        "Name": "build",
        "Short": "Compile the package",
        "LocalFlags": [{"Longhand": "release", "Shorthand": "r", "Usage": "Build in release mode", "Type": "bool"}]
    }]
}"#;

#[test]
fn reads_piped_help_text() -> Result {
    test()
        .run_with_data("generate completions tool --source help", HELP)
        .expect_value_eq(indoc::indoc! {r#"
            # Generated by `generate completions` from help text piped in.
            # Flags that are not declared here still reach `tool`. Arguments without a completer
            # here are completed by the external completer in $env.config.completions.external.

            # Not declared (optional value or unsupported name): --color
            @complete external
            export extern "tool" [
                --output(-o): string           # Write output to FILE
                --format: string@[json 'true' '2'] # Output format [possible values: json, true, 2]
                --help(-h)                     # Print help
            ]
        "#})
}

#[rstest]
#[case::help("help", HELP, "tool")]
#[case::man("man", HELP, "tool")]
#[case::help_subcommands("help", CLAP_HELP, "tool install")]
#[case::fish("fish", FISH, "tool build")]
#[case::zsh("zsh", ZSH, "tool build")]
#[case::carapace("carapace", CARAPACE, "tool build")]
fn generated_module_parses(
    #[case] source: &str,
    #[case] text: &str,
    #[case] defines: &str,
) -> Result {
    let code = r#"
        let case = $in
        let module = $case.text | generate completions tool --source $case.source
        {
            parses: ($module | nu-check --as-module)
            defines: ($module | str contains $'export extern "($case.defines)" [')
        }
    "#;
    let data = test_record! { "source" => source, "text" => text, "defines" => defines };
    test()
        .run_with_data(code, data)
        .expect_value_eq(test_record! { "parses" => true, "defines" => true })
}

/// `use` names the module after the file, and a module can't export an extern with its own
/// name, so a module loaded with `use` is saved under a name other than the tool's.
#[test]
fn loads_with_use_from_a_completions_file() -> Result {
    Playground::setup("generate_completions_use", |dirs, _| {
        let mut tester = test().cwd(dirs.test());
        let () = tester.run_with_data(
            "generate completions tool --source fish | save tool-completions.nu",
            FISH,
        )?;
        tester
            .run("use tool-completions.nu *; scope externs | get name | where $it starts-with tool | sort")
            .expect_value_eq(["tool", "tool build"])
    })
}

/// A man page's command list is left out: it is mostly the commands of an interactive prompt.
#[rstest]
#[case::help("help", &["tool pip", "tool pip install", "tool pip i", "tool pip list"])]
#[case::man("man", &["tool pip"])]
fn reads_the_subcommands_the_help_lists(#[case] source: &str, #[case] externs: &[&str]) -> Result {
    let code = format!(
        "generate completions 'tool pip' --source {source} | lines | parse --regex '^export extern \"(?<name>[^\"]+)\"' | get name"
    );
    test()
        .run_with_data(code, CLAP_HELP)
        .expect_value_eq(externs.to_vec())
}

